-- ============================================================
-- Multi-tenancy, stage A: schema + backfill only - no Java code
-- in this deploy assumes these columns exist yet, so this is
-- safe to ship and verify entirely on its own first.
--
-- Creates one organization for the existing gym and backfills
-- every current row to point at it, so nothing about today's
-- single-tenant behavior changes until the stage B application
-- code (which actually starts scoping queries by organization_id)
-- ships separately.
-- ============================================================

CREATE TABLE organizations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(200) NOT NULL,
    created_at  TIMESTAMP NOT NULL DEFAULT now(),
    updated_at  TIMESTAMP NOT NULL DEFAULT now()
);

INSERT INTO organizations (name) VALUES ('Takedown Martial Arts');

ALTER TABLE tournaments ADD COLUMN organization_id BIGINT REFERENCES organizations (id);
ALTER TABLE athletes ADD COLUMN organization_id BIGINT REFERENCES organizations (id);
ALTER TABLE users ADD COLUMN organization_id BIGINT REFERENCES organizations (id);

UPDATE tournaments SET organization_id = (SELECT id FROM organizations LIMIT 1) WHERE organization_id IS NULL;
UPDATE athletes SET organization_id = (SELECT id FROM organizations LIMIT 1) WHERE organization_id IS NULL;
UPDATE users SET organization_id = (SELECT id FROM organizations LIMIT 1) WHERE organization_id IS NULL;

CREATE INDEX idx_tournament_organization ON tournaments (organization_id);
CREATE INDEX idx_athlete_organization ON athletes (organization_id);
CREATE INDEX idx_user_organization ON users (organization_id);
